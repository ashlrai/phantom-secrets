#!/usr/bin/env bash
# Usage: scripts/resolve-merge-conflicts.sh — run while a rebase, merge, or
# cherry-pick is stopped on conflicts. Resolves the mechanical cases without
# any model call:
#
#   CHANGELOG.md             union of both sides (when .gitattributes
#                            merge=union is already active the driver resolves
#                            it before this script ever sees the file)
#   CLAUDE.md / README.md    upstream version, then the lane's own patch
#                            (merge-base -> lane blob) re-applied with
#                            `git apply --reject`; hunks that no longer apply
#                            are reported so a human can re-add them by hand
#   Cargo.lock               upstream lockfile; if `cargo metadata --locked`
#                            still verifies, nothing changes (zero churn),
#                            else `cargo generate-lockfile` re-resolves keeping
#                            every version that still satisfies the manifests
#   bun.lock / bun.lockb     upstream lockfile, then `bun install`
#   package-lock.json        upstream lockfile, then
#                            `npm install --package-lock-only`
#
# Manifests (Cargo.toml, package.json) are inputs and are never edited.
# Lockfiles are regenerated by the package manager, never hand-merged.
# Anything outside this list is left conflicted; exit status is 1 while any
# unmerged path remains.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

gitdir=$(git rev-parse --git-dir)
# `git merge upstream` on a lane: stage 3 is upstream, stage 2 is the lane.
# Rebase / cherry-pick / revert: stage 2 is the upstream tip being replayed
# onto, stage 3 is the lane's commit.
if [[ -f "$gitdir/MERGE_HEAD" ]]; then upstream=3; lane=2; else upstream=2; lane=3; fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

blob() {
    git show ":$1:$2" > "$tmp/blob.$1" 2>/dev/null && cp "$tmp/blob.$1" "$3"
}

resolve_union() {
    local path=$1
    : > "$tmp/base"; : > "$tmp/up"; : > "$tmp/lane"
    blob 1 "$path" "$tmp/base" || true
    blob "$upstream" "$path" "$tmp/up" || true
    blob "$lane" "$path" "$tmp/lane" || true
    git merge-file --union -p "$tmp/up" "$tmp/base" "$tmp/lane" > "$path"
    git add "$path"
    echo "  ok $path (union of both sides)"
}

resolve_reapply() {
    local path=$1
    if ! blob "$upstream" "$path" "$path"; then
        echo "  !  $path: no upstream stage, left for manual resolution" >&2
        return 1
    fi
    local rejects=0 apply_rc=0
    if ! git diff ":1:$path" ":$lane:$path" > "$tmp/lane.patch" 2> "$tmp/diff.err"; then
        echo "  !  $path: could not extract the lane patch:" >&2
        cat "$tmp/diff.err" >&2
        return 1
    fi
    if [[ -s "$tmp/lane.patch" ]]; then
        rm -f "$path.rej"
        git apply --reject --whitespace=nowarn "$tmp/lane.patch" 2> "$tmp/apply.err" || apply_rc=$?
        if [[ -f "$path.rej" ]]; then
            # grep -c exits 1 on a zero count; exit 2 is a real read error.
            rejects=$(grep -c '^@@' "$path.rej" || (( $? == 1 ))) || {
                echo "  !  $path: could not count rejected hunks" >&2
                return 1
            }
            echo "  ~  $path: upstream version kept; $rejects lane hunk(s) did not apply:" >&2
            cat "$path.rej" >&2
            rm -f "$path.rej"
        elif (( apply_rc )); then
            echo "  !  $path: lane patch failed without leaving rejects:" >&2
            cat "$tmp/apply.err" >&2
            return 1
        fi
    fi
    git add "$path"
    ((rejects)) || echo "  ok $path (upstream + lane hunks)"
}

resolve_lock() {
    local path=$1
    local dir how="regenerated"
    dir=$(dirname "$path")
    if ! blob "$upstream" "$path" "$path"; then
        echo "  !  $path: no upstream stage, left for manual resolution" >&2
        return 1
    fi
    case $(basename "$path") in
        Cargo.lock)
            command -v cargo > /dev/null || { echo "  !  $path: cargo not on PATH" >&2; return 1; }
            if (cd "$dir" && cargo metadata --locked --format-version 1 > /dev/null 2>&1); then
                how="already consistent, zero churn"
            else
                (cd "$dir" && cargo generate-lockfile && cargo metadata --locked --format-version 1 > /dev/null)
            fi
            ;;
        # Lock regeneration must not execute package lifecycle hooks.
        bun.lock | bun.lockb)
            command -v bun > /dev/null || { echo "  !  $path: bun not on PATH" >&2; return 1; }
            (cd "$dir" && bun install --ignore-scripts)
            ;;
        package-lock.json)
            command -v npm > /dev/null || { echo "  !  $path: npm not on PATH" >&2; return 1; }
            (cd "$dir" && npm install --package-lock-only --ignore-scripts)
            ;;
    esac && { git add "$path"; echo "  ok $path ($how)"; } || {
        echo "  !  $path: package manager could not regenerate it" >&2; return 1; }
}

declare -a manual=()
while IFS= read -r -d '' path; do
    case $(basename "$path") in
        CHANGELOG.md) resolve_union "$path" || manual+=("$path") ;;
        CLAUDE.md | README.md) resolve_reapply "$path" || manual+=("$path") ;;
        Cargo.lock | bun.lock | bun.lockb | package-lock.json) resolve_lock "$path" || manual+=("$path") ;;
        *) manual+=("$path") ;;
    esac
done < <(git diff --name-only --diff-filter=U -z)

if ((${#manual[@]})); then
    echo "left conflicted for manual resolution:" >&2
    printf '  %s\n' "${manual[@]}" >&2
    exit 1
fi
echo "all conflicts resolved"
