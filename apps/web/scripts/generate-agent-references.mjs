import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const WEB_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPO_ROOT = path.resolve(WEB_ROOT, "../..");
const SITE_URL = "https://phm.dev";
const REPOSITORY = "https://github.com/ashlrai/phantom-secrets/blob/main";
const read = (file) => readFileSync(path.join(REPO_ROOT, file), "utf8");
const plain = (text) => text.replace(/\[([^\]]+)\]\([^)]+\)/g, "$1").replace(/[`*_]/g, "").replace(/\u2014/g, " - ");

// Match public MarkdownDocument anchors, including repeated headings. README
// links use GitHub's duplicate suffix and preserve its repeated hyphens.
export function extractHeadings(markdown, github = false) {
  const headings = [];
  const counts = new Map();
  let fence;
  for (const line of markdown.split(/\r?\n/)) {
    const marker = /^ {0,3}(`{3,}|~{3,})(.*)$/.exec(line);
    if (marker) {
      if (!fence) fence = { char: marker[1][0], length: marker[1].length };
      else if (marker[1][0] === fence.char && marker[1].length >= fence.length && !marker[2].trim()) fence = undefined;
      continue;
    }
    if (fence) continue;
    const heading = /^(#{1,6})\s+(.+?)(?:\s+#+\s*)?$/.exec(line);
    if (!heading) continue;
    const title = plain(heading[2]);
    let anchor = heading[2].toLowerCase().replace(/`([^`]+)`/g, "$1")
      .replace(/[^a-z0-9\s-]/g, "").trim().replace(/\s/g, "-");
    if (!github) anchor = anchor.replace(/-+/g, "-");
    const count = counts.get(anchor) ?? 0;
    counts.set(anchor, count + 1);
    headings.push({ level: heading[1].length, title, anchor: count ? `${anchor}-${count + (github ? 0 : 1)}` : anchor });
  }
  return headings;
}

export function generateReferences() {
  const readme = read("README.md");
  const catalog = JSON.parse(read("apps/web/docs-catalog.json"));
  const cargo = read("Cargo.toml");
  const workspace = cargo.split("[workspace.package]")[1]?.split("\n[")[0];
  const version = /^version = "([^"]+)"/m.exec(workspace ?? "")?.[1];
  const license = /^license = "([^"]+)"/m.exec(workspace ?? "")?.[1];
  const crateCount = (cargo.split("[workspace.package]")[0].match(/"crates\//g) ?? []).length;
  if (!version || !license || !crateCount) throw new Error("Missing workspace version, license, or members");
  // Select the bounded product explanation, excluding README badges and HTML.
  const explanation = /^(Phantom replaces project secrets[^\n]+)$/m.exec(readme)?.[1];
  if (!explanation) throw new Error("README product explanation is missing; review the generation source");
  const summary = `## From the README\n\n${explanation}\n\nSource version: ${version}. License: ${license}. Source version is not publication evidence.\n\n- [Capabilities and installation](${SITE_URL}/secrets/capabilities): Supported workflows, exact release installation, agent setup, and authority boundaries.\n\n`;
  const readmeIndex = "## README sections\n\n" + extractHeadings(readme, true)
    .filter(({ level }) => level === 2)
    .map(({ title, anchor }) => `- [${title}](${REPOSITORY}/README.md#${anchor})`).join("\n");
  const docsIndex = "## Canonical documentation and headings\n\n" + catalog.map(({ slug, file, description }) => {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*\.md$/.test(file) || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) throw new Error("Unsafe documentation catalog path");
    const headings = extractHeadings(read(`docs/${file}`));
    if (headings.filter(({ level }) => level === 1).length !== 1) throw new Error(`Expected one document title: ${file}`);
    const title = headings.find(({ level }) => level === 1).title;
    const url = `${SITE_URL}/docs/${slug}`;
    return `### ${title}\n\n- [${title}](${url}): ${plain(description)}\n` + headings.filter(({ level }) => level > 1)
      .map(({ title: section, anchor }) => `- [${section}](${url}#${anchor})`).join("\n");
  }).join("\n\n");
  const outputs = new Map();
  for (const [kind, filename] of [["compact", "llms.txt"], ["full", "llms-full.txt"]]) {
    let narrative = read(`apps/web/agent-reference/${kind}.md`).replaceAll("{{WORKSPACE_CRATE_COUNT}}", String(crateCount)).trim();
    for (const { slug, file } of catalog) narrative = narrative.replaceAll(`${REPOSITORY}/docs/${file}`, `${SITE_URL}/docs/${slug}`);
    const firstBreak = narrative.indexOf("\n");
    const provenance = `\n\n> Generated by apps/web/scripts/generate-agent-references.mjs from README.md, docs headings, Cargo.toml, and the reviewed ${kind} reference. Do not edit generated copies.\n\n`;
    // Keep the original introductory paragraph directly under the title, then
    // place the generated README summary before the first product section.
    const firstSection = narrative.indexOf("\n## ", firstBreak);
    if (firstSection < 0) throw new Error(`Missing product sections in ${kind} reference`);
    const text = (narrative.slice(0, firstBreak) + provenance + narrative.slice(firstBreak, firstSection).trim() + "\n\n" + summary + narrative.slice(firstSection).trimStart() + "\n\n" + readmeIndex + "\n\n" + docsIndex + "\n").replace(/\u2014/g, " - ");
    outputs.set(`apps/web/public/${filename}`, text);
    outputs.set(`docs/${filename}`, text);
  }
  // Read the app's route declarations rather than maintain a second sitemap.
  const pages = [...read("apps/web/src/app/sitemap.ts").matchAll(/\{ path: "([^"]+)", modified: "(\d{4}-\d{2}-\d{2})" \}/g)]
    .map(([, route, modified]) => ({ route, modified }));
  if (!pages.length) throw new Error("No sitemap routes found; review the app sitemap format");
  pages.push(...catalog.map(({ slug, modified }) => ({ route: `/docs/${slug}`, modified })));
  const escapeXml = (value) => value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll('"', "&quot;");
  outputs.set("docs/sitemap.xml", '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + pages.map(({ route, modified }) => `  <url><loc>${escapeXml(new URL(route, SITE_URL).href)}</loc><lastmod>${modified}</lastmod></url>`).join("\n") + "\n</urlset>\n");
  return outputs;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== "--check")) throw new Error("Usage: node scripts/generate-agent-references.mjs [--check]");
  let stale = false;
  for (const [file, expected] of generateReferences()) {
    if (args.includes("--check")) {
      let actual;
      try { actual = read(file); } catch { actual = undefined; }
      if (actual !== expected) { console.error(`Stale generated reference: ${file}`); stale = true; }
    } else writeFileSync(path.join(REPO_ROOT, file), expected);
  }
  if (stale) process.exitCode = 1;
}
